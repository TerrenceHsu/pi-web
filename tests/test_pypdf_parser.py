class TestOptionalDependencyMissing:
    def test_pypdf_missing_raises_unavailable(self, monkeypatch):
        """Simulate pypdf not installed — PypdfParser() must raise
        PdfParserUnavailable, not ImportError."""
        # Hide pypdf from importlib
        real_import = __import__

        def fake_import(name, *args, **kwargs):
            if name == "pypdf" or name.startswith("pypdf."):
                raise ImportError(f"simulated: no module named {name!r}")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr("builtins.__import__", fake_import)
        with pytest.raises(PdfParserUnavailable):
            PypdfParser()

    def test_safe_error_code_on_unavailable(self, monkeypatch):
        real_import = __import__

        def fake_import(name, *args, **kwargs):
            if name == "pypdf" or name.startswith("pypdf."):
                raise ImportError("simulated")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr("builtins.__import__", fake_import)
        try:
            PypdfParser()
        except PdfParserUnavailable as e:
            assert e.safe_error_code == "pdf_parser_unavailable"
            # Message must not contain site-packages path / pip hint with paths
            assert "site-packages" not in str(e)


