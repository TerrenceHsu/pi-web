class TestSecurityBoundary:
    def test_no_network_imports_in_adapter(self) -> None:
        """Adapter module must not import any network / OCR / model / LLM libs."""
        from pi_agent_core_py.web.knowledge import pypdf_parser

        text = Path(pypdf_parser.__file__).read_text(encoding="utf-8")
        forbidden = [
            "import requests",
            "from requests",
            "import httpx",
            "from httpx",
            "import urllib",
            "from urllib",
            "import aiohttp",
            "from aiohttp",
            "import openai",
            "from openai",
            "import anthropic",
            "from anthropic",
            "google.genai",
            "import torch",
            "from torch",
            "import transformers",
            "from transformers",
            "import surya",
            "from surya",
            "import fitz",
            "from fitz",
            "import pymupdf",
            "from pymupdf",
            "huggingface_hub",
            "huggingface-hub",
        ]
        for token in forbidden:
            assert token not in text, (
                f"forbidden import {token!r} found in pypdf_parser.py"
            )

    def test_no_markdown_generation(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        # Result must not contain markdown artifacts (frontmatter, headings,
        # page markers). Those are R2-B's job.
        for page in res.pages:
            assert "<!-- page:" not in page.text
            assert "---\n" not in page.text[:50]  # no YAML frontmatter
            assert not page.text.startswith("# ")

    def test_error_messages_no_absolute_path(self, parser, tmp_path):
        """All error messages must omit absolute paths."""
        missing = tmp_path / "nope.pdf"
        try:
            parser.inspect(missing)
        except PdfParserError as e:
            msg = str(e)
            assert str(tmp_path) not in msg
            assert ":\\" not in msg.lower() or "c:" not in msg.lower()
        else:
            pytest.fail("expected PdfParserError")

    def test_error_messages_no_pypdf_traceback(self, parser, corrupted_pdf):
        try:
            parser.inspect(corrupted_pdf)
        except InvalidPdf as e:
            msg = str(e)
            # No pypdf internal class names in message
            assert "PdfReader" not in msg
            assert "traceback" not in msg.lower()

    def test_pypdf_only_imported_in_adapter_module(self) -> None:
        """Walk all .py in src except pypdf_parser.py — none should import pypdf."""
        import re
        from pathlib import Path as P

        src_root = P(__file__).resolve().parent.parent / "src"
        offenders: list[str] = []
        for py in src_root.rglob("*.py"):
            if py.name == "pypdf_parser.py":
                continue
            text = py.read_text(encoding="utf-8", errors="ignore")
            if re.search(r"^\s*(import pypdf|from pypdf)", text, re.MULTILINE):
                offenders.append(str(py.relative_to(src_root)))
        assert offenders == [], (
            f"pypdf must only be imported in pypdf_parser.py; found in: {offenders}"
        )


