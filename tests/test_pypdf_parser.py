class TestInspect:
    def test_single_page(self, parser, single_page_text_pdf):
        ins = parser.inspect(single_page_text_pdf)
        assert ins.page_count == 1
        assert ins.encrypted is False
        assert ins.password_required is False

    def test_multi_page_count(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        assert ins.page_count == 2

    def test_file_size_bytes_positive(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        assert ins.file_size_bytes > 0

    def test_metadata_extracted(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        assert ins.metadata.title == "Test PDF"
        assert ins.metadata.author == "R2-A Tests"

    def test_blank_pdf_has_text_false(self, parser, blank_pdf):
        ins = parser.inspect(blank_pdf)
        assert ins.has_extractable_text_estimate is False

    def test_text_pdf_has_text_true(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        assert ins.has_extractable_text_estimate is True

    def test_encrypted_pdf_password_required(self, parser, encrypted_pdf):
        ins = parser.inspect(encrypted_pdf)
        assert ins.encrypted is True
        assert ins.password_required is True
        assert ins.page_count == 0  # cannot probe without password
        assert ins.has_extractable_text_estimate is None

    def test_encrypted_pdf_has_warning(self, parser, encrypted_pdf):
        ins = parser.inspect(encrypted_pdf)
        assert any("encrypted" in w for w in ins.inspection_warnings)

    def test_corrupted_pdf_raises_invalid(self, parser, corrupted_pdf):
        with pytest.raises(InvalidPdf):
            parser.inspect(corrupted_pdf)

    def test_nonexistent_path_raises(self, parser, tmp_path):
        with pytest.raises(PdfFileNotFound):
            parser.inspect(tmp_path / "does_not_exist.pdf")

    def test_directory_path_raises_not_a_file(self, parser, tmp_path):
        with pytest.raises((PdfNotAFile, PdfParserError)):
            parser.inspect(tmp_path)

    def test_file_handle_released(self, parser, text_pdf):
        # On Windows, an unclosed file handle would block deletion.
        parser.inspect(text_pdf)
        # Should be deletable without error
        text_pdf.unlink()

    def test_consecutive_inspect_stable(self, parser, text_pdf):
        a = parser.inspect(text_pdf)
        b = parser.inspect(text_pdf)
        assert a.page_count == b.page_count
        assert a.file_size_bytes == b.file_size_bytes
        assert a.has_extractable_text_estimate == b.has_extractable_text_estimate


