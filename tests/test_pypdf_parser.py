class TestModelsAndProtocol:
    def test_pdf_inspection_is_frozen(self) -> None:
        ins = PdfInspection(
            file_size_bytes=100,
            page_count=1,
            encrypted=False,
            password_required=False,
            metadata=PdfMetadata(),
            has_extractable_text_estimate=True,
        )
        with pytest.raises((AttributeError, Exception)):
            ins.file_size_bytes = 200  # type: ignore[misc]

    def test_pdf_page_is_frozen(self) -> None:
        page = PdfPage(page_number=1, text="hello")
        with pytest.raises((AttributeError, Exception)):
            page.text = "modified"  # type: ignore[misc]

    def test_pdf_page_1_based(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        assert res.pages[0].page_number == 1
        assert res.pages[1].page_number == 2

    def test_extraction_result_pages_is_tuple(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        assert isinstance(res.pages, tuple)
        assert all(isinstance(p, PdfPage) for p in res.pages)

    def test_inspection_warnings_is_tuple(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        assert isinstance(ins.inspection_warnings, tuple)

    def test_metadata_repr_no_absolute_path(self, parser, text_pdf):
        ins = parser.inspect(text_pdf)
        # PdfMetadata and PdfInspection repr must not contain absolute path
        assert "tmp_path" not in repr(ins)
        assert ":\\" not in repr(ins).lower() or "c:" not in repr(ins).lower()

    def test_extraction_result_no_pypdf_object_leak(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        # Walk all attributes recursively — must not find a pypdf PageObject
        text = repr(res)
        assert "PageObject" not in text
        assert "PdfReader" not in text

    def test_parser_protocol_runtime_checkable(self, parser):
        # @runtime_checkable Protocol — isinstance should pass
        assert isinstance(parser, PdfParser)

    def test_parser_protocol_has_required_methods(self):
        # Static check — Protocol declares parser_id, parser_version, inspect,
        # extract, close
        assert hasattr(PdfParser, "parser_id")
        assert hasattr(PdfParser, "parser_version")
        assert hasattr(PdfParser, "inspect")
        assert hasattr(PdfParser, "extract")
        assert hasattr(PdfParser, "close")


