class TestPageLevelFailure:
    def test_page_extract_failure_terminates_whole_extract(
        self, parser, text_pdf
    ):
        """Per P2-R2-A §17 option A — single page failure must terminate the
        whole extract (no silent missing pages)."""
        from pypdf import PageObject

        # Patch the second page's extract_text to raise
        original = PageObject.extract_text

        call_count = {"n": 0}

        def boom(self, *args, **kwargs):
            call_count["n"] += 1
            if call_count["n"] == 2:
                raise RuntimeError("simulated page extract failure")
            return original(self, *args, **kwargs)

        with patch.object(PageObject, "extract_text", boom):
            with pytest.raises(PdfPageExtractFailed):
                parser.extract(text_pdf)


