class TestExtract:
    def test_single_page_text(self, parser, single_page_text_pdf):
        res = parser.extract(single_page_text_pdf)
        assert len(res.pages) == 1
        assert "Only one page" in res.pages[0].text

    def test_multi_page_order(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        assert len(res.pages) == 2
        assert "Hello World page 1" in res.pages[0].text
        assert "Another page 2" in res.pages[1].text

    def test_page_numbers_sequential_1_based(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        numbers = [p.page_number for p in res.pages]
        assert numbers == [1, 2]

    def test_parser_id_and_version_in_result(self, parser, text_pdf):
        res = parser.extract(text_pdf)
        assert res.parser_id == "pypdf"
        assert res.parser_version == parser.parser_version

    def test_blank_page_returns_empty_string_not_none(self, parser, blank_pdf):
        res = parser.extract(blank_pdf)
        for page in res.pages:
            assert page.text == ""
            assert isinstance(page.text, str)

    def test_crlf_normalized(self, parser, tmp_path):
        # Inject CRLF via raw text — fixture helper escapes newlines to space,
        # but if pypdf returns \r\n in extraction, adapter should normalize.
        # Test by checking adapter._normalize_text directly.
        from pi_agent_core_py.web.knowledge.pypdf_parser import PypdfParser
        assert PypdfParser._normalize_text("a\r\nb\rc") == "a\nb\nc"

    def test_nul_bytes_stripped(self, parser):
        from pi_agent_core_py.web.knowledge.pypdf_parser import PypdfParser
        assert PypdfParser._normalize_text("a\x00b") == "ab"

    def test_none_text_becomes_empty(self, parser):
        from pi_agent_core_py.web.knowledge.pypdf_parser import PypdfParser
        assert PypdfParser._normalize_text(None) == ""

    def test_encrypted_pdf_rejected(self, parser, encrypted_pdf):
        with pytest.raises(PdfPasswordRequired):
            parser.extract(encrypted_pdf)

    def test_corrupted_pdf_rejected(self, parser, corrupted_pdf):
        with pytest.raises(InvalidPdf):
            parser.extract(corrupted_pdf)

    def test_nonexistent_rejected(self, parser, tmp_path):
        with pytest.raises(PdfFileNotFound):
            parser.extract(tmp_path / "nope.pdf")

    def test_source_pdf_not_modified(self, parser, text_pdf):
        sha_before = file_sha256(text_pdf)
        parser.inspect(text_pdf)
        parser.extract(text_pdf)
        sha_after = file_sha256(text_pdf)
        assert sha_before == sha_after

    def test_close_idempotent(self, parser):
        parser.close()
        parser.close()  # second close must not raise

    def test_extract_after_close_raises(self, parser, text_pdf):
        parser.close()
        with pytest.raises(PdfParserError):
            parser.extract(text_pdf)

    def test_consecutive_extract_stable(self, parser, text_pdf):
        a = parser.extract(text_pdf)
        b = parser.extract(text_pdf)
        assert len(a.pages) == len(b.pages)
        for pa, pb in zip(a.pages, b.pages, strict=True):
            assert pa.text == pb.text


